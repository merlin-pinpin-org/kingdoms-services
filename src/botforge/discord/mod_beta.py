"""The mod's BETA console surface — the registered actions' buttons.

The mod's admin menu (``menu:mod:<name>:admin``, generated by the SDK)
carries the beta section: the phase toggle (enter/leave) and the mod's
registered beta actions — guarded, ephemeral, the 3-second rule
(defer, then followup). The mod owns the actions (its mechanics); the
SDK owns the plumbing (never a hand-rolled console per mod).
"""

from __future__ import annotations

import logging
from typing import Any

import discord

from botforge.core.services.beta import (
    beta_action,
    enter_beta,
    exit_beta,
    is_beta,
    registered_beta_actions,
)

logger = logging.getLogger("botforge.discord.mod_beta")

_NS = "modbeta"


async def _beta_guard(interaction: discord.Interaction) -> bool:
    """Guard the beta console: bot-admin only, checked at click time."""
    from botforge.discord.guards import require_admin

    bot = interaction.client
    admins = tuple(getattr(getattr(bot, "status_service", None), "bot_admins", ()) or ())
    return bool(await require_admin(interaction, admins))


class BetaActionButton(
    discord.ui.DynamicItem[discord.ui.Button[Any]],
    template=rf"{_NS}:(?P<mod>[a-z0-9_-]+):(?P<key>[a-z0-9_-]+)",
):
    """One registered beta action's button: the twist on demand."""

    def __init__(self, mod: str, key: str, label: str, emoji: str = "") -> None:
        super().__init__(
            discord.ui.Button(
                custom_id=f"{_NS}:{mod}:{key}"[:100],
                label=label[:80],
                emoji=discord.PartialEmoji.from_str(emoji) if emoji else None,
                style=discord.ButtonStyle.secondary,
            )
        )
        self.mod = mod
        self.key = key

    @classmethod
    async def from_custom_id(
        cls,
        interaction: discord.Interaction,
        item: discord.ui.Item[Any],
        match: Any,
        /,
    ) -> BetaActionButton:
        """Rebuild the button from its custom id at click time."""
        button = item if isinstance(item, discord.ui.Button) else None
        label = (button.label or "?") if button is not None else "?"
        emoji = button.emoji.name if button is not None and isinstance(button.emoji, discord.PartialEmoji) else ""
        return cls(match["mod"], match["key"], label, emoji)

    async def callback(self, interaction: discord.Interaction) -> None:
        """Run the registered twist (guarded, ephemeral, 3-second rule)."""
        if not await _beta_guard(interaction):
            return
        action = beta_action(self.mod, self.key)
        if action is None:
            await interaction.response.send_message(
                "This beta action is no longer registered.", ephemeral=True
            )
            return
        await interaction.response.defer(ephemeral=True)
        try:
            report = await action.handler(interaction.client, str(interaction.guild_id or ""))
        except Exception:
            logger.warning("BETA: the %s/%s action failed", self.mod, self.key, exc_info=True)
            report = "The action failed — see the logs."
        await interaction.followup.send(str(report)[:2000], ephemeral=True)


class BetaPhaseButton(
    discord.ui.DynamicItem[discord.ui.Button[Any]],
    template=rf"{_NS}:phase:(?P<mod>[a-z0-9_-]+)",
):
    """The beta phase toggle: enter or leave (the operator's call)."""

    def __init__(self, mod: str, label: str, active: bool) -> None:
        super().__init__(
            discord.ui.Button(
                custom_id=f"{_NS}:phase:{mod}"[:100],
                label=label[:80],
                emoji="\U0001f9ea",
                style=discord.ButtonStyle.success if not active else discord.ButtonStyle.danger,
            )
        )
        self.mod = mod
        self.active = active

    @classmethod
    async def from_custom_id(
        cls,
        interaction: discord.Interaction,
        item: discord.ui.Item[Any],
        match: Any,
        /,
    ) -> BetaPhaseButton:
        """Rebuild the toggle from its custom id at click time."""
        button = item if isinstance(item, discord.ui.Button) else None
        label = (button.label or "?") if button is not None else "?"
        return cls(match["mod"], label, False)

    async def callback(self, interaction: discord.Interaction) -> None:
        """Flip the phase (guarded, ephemeral)."""
        from botforge.core.services.mod_storage import ModStateCache
        from botforge.discord.scope_pins import _tr

        if not await _beta_guard(interaction):
            return
        await interaction.response.defer(ephemeral=True)
        state_service = getattr(interaction.client, "state_service", None)
        cache = ModStateCache(state_service, self.mod) if state_service is not None else None
        guild_id = str(interaction.guild_id or "")
        if await is_beta(cache, guild_id, self.mod):
            await exit_beta(cache, guild_id, self.mod)
            note = _tr(None, "ui.beta.exited", "fr", "Beta phase left — the rules straighten back.")
        else:
            await enter_beta(cache, guild_id, self.mod)
            note = _tr(None, "ui.beta.entered", "fr", "Beta phase entered — the rules bend.")
        await interaction.followup.send(note, ephemeral=True)


async def beta_console_buttons(bot: Any, guild_id: str, mod: str, tr: Any) -> list[Any]:
    """Build the mod's beta console buttons (the admin menu's section).

    The phase toggle first (its label reflects the current state), then
    the registered actions in the registration order.
    """
    from botforge.core.services.mod_storage import ModStateCache

    state_service = getattr(bot, "state_service", None)
    cache = ModStateCache(state_service, mod) if state_service is not None else None
    active = await is_beta(cache, guild_id, mod)
    toggle_label = tr(
        None, "ui.beta.btn_leave" if active else "ui.beta.btn_enter", "fr",
        "Leave the beta phase" if active else "Enter the beta phase",
    )
    out: list[Any] = [BetaPhaseButton(mod, toggle_label, active)]
    for action in registered_beta_actions(mod):
        label = tr(None, action.label_key, "fr", action.key)
        out.append(BetaActionButton(mod, action.key, label, action.emoji))
    return out


__all__ = ["BetaActionButton", "BetaPhaseButton", "beta_console_buttons"]
